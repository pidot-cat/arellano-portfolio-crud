import { Link, router } from '@inertiajs/react';
import { useState } from 'react';
import AdminLayout from '../../Layouts/AdminLayout';
import ConfirmDeleteModal from '../../Components/ConfirmDeleteModal';

export default function Index({ projects, filters }) {
    const [search, setSearch] = useState(filters.search ?? '');
    const [toDelete, setToDelete] = useState(null);
    const [deleting, setDeleting] = useState(false);

    const submitSearch = (e) => {
        e.preventDefault();
        router.get('/projects', { search }, { preserveState: true });
    };

    const confirmDelete = () => {
        router.delete(`/projects/${toDelete.id}`, {
            onStart: () => setDeleting(true),
            onFinish: () => { setDeleting(false); setToDelete(null); },
        });
    };

    return (
        <AdminLayout title="My Projects">
            <div className="mb-5 flex flex-wrap items-center justify-between gap-3">
                <form onSubmit={submitSearch} className="flex gap-2">
                    <input value={search} onChange={(e) => setSearch(e.target.value)} placeholder="Search title or category…"
                        className="rounded-lg border border-white/10 bg-[#12121f] px-3 py-2 text-white" />
                    <button className="rounded-lg border border-white/20 px-4 py-2 hover:bg-white/5">Search</button>
                </form>
                <Link href="/projects/create"
                    className="rounded-lg bg-gradient-to-br from-violet-600 to-violet-400 px-5 py-2 font-semibold text-white">
                    <i className="fas fa-plus mr-1"></i> Add Project
                </Link>
            </div>

            <div className="overflow-x-auto rounded-2xl border border-white/10 bg-[#1a1a2e]">
                <table className="w-full text-left text-sm">
                    <thead className="bg-white/5 text-violet-200">
                        <tr>
                            <th className="p-3">Image</th>
                            <th className="p-3">Title</th>
                            <th className="p-3">Category</th>
                            <th className="p-3">Completed</th>
                            <th className="p-3 text-right">Actions</th>
                        </tr>
                    </thead>
                    <tbody>
                        {projects.data.length === 0 && (
                            <tr><td colSpan="5" className="p-6 text-center text-gray-400">No projects found.</td></tr>
                        )}
                        {projects.data.map((p) => (
                            <tr key={p.id} className="border-t border-white/5">
                                <td className="p-3"><img src={p.image_url} alt={p.title} className="h-12 w-16 rounded object-cover" /></td>
                                <td className="p-3 font-semibold">{p.title}</td>
                                <td className="p-3 text-gray-300">{p.category}</td>
                                <td className="p-3 text-gray-300">{p.date_completed}</td>
                                <td className="p-3 text-right whitespace-nowrap">
                                    <Link href={`/projects/${p.id}/edit`} className="mr-2 rounded bg-violet-600/80 px-3 py-1 hover:bg-violet-500">
                                        <i className="fas fa-edit"></i> Edit
                                    </Link>
                                    <button onClick={() => setToDelete(p)} className="rounded bg-red-600/80 px-3 py-1 hover:bg-red-500">
                                        <i className="fas fa-trash"></i> Delete
                                    </button>
                                </td>
                            </tr>
                        ))}
                    </tbody>
                </table>
            </div>

            {/* Pagination links generated by Laravel's paginate() */}
            <div className="mt-4 flex flex-wrap gap-1">
                {projects.links.map((link, i) => (
                    <Link key={i} href={link.url ?? '#'} preserveScroll
                        className={`rounded px-3 py-1 text-sm ${link.active ? 'bg-violet-600' : 'border border-white/10'} ${!link.url ? 'pointer-events-none opacity-40' : ''}`}
                        dangerouslySetInnerHTML={{ __html: link.label }} />
                ))}
            </div>

            <ConfirmDeleteModal project={toDelete} processing={deleting}
                onConfirm={confirmDelete} onCancel={() => setToDelete(null)} />
        </AdminLayout>
    );
}
